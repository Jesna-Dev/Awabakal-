type VectorPortraitProps = {
  /** unique per instance — clip paths are referenced by id */
  id: string;
  src: string;
  alt: string;
  /** rendered size in px, used for the image `sizes` hint */
  size: number;
  /** which blob to mask with */
  shape?: keyof typeof SHAPES;
  /** optional colour wash laid over the photo — include the alpha yourself */
  overlay?: string;
  className?: string;
};

/**
 * A blob vector used as a mask: the photo fills the shape exactly, scaled to
 * the element via an objectBoundingBox clip path.
 */
export default function VectorPortrait({
  id,
  src,
  alt,
  size,
  shape = "vector-2534",
  overlay,
  className,
}: VectorPortraitProps) {
  const { width, height, path } = SHAPES[shape];

  return (
    <div
      className={`relative ${className ?? ""}`}
      style={{ aspectRatio: `${width} / ${height}` }}
    >
      <svg aria-hidden className="absolute size-0">
        <defs>
          <clipPath id={id} clipPathUnits="objectBoundingBox">
            {/* the shape's own artboard normalised to 0..1 */}
            <path d={path} transform={`scale(${1 / width} ${1 / height})`} />
          </clipPath>
        </defs>
      </svg>

      <Image
        src={src}
        alt={alt}
        fill
        sizes={`${size}px`}
        className="object-cover"
        style={{ clipPath: `url(#${id})` }}
      />

      {overlay && (
        // clipped to the same blob so the wash stops at the photo's edge
        <div
          aria-hidden
          className="pointer-events-none absolute inset-0"
          style={{ background: overlay, clipPath: `url(#${id})` }}
        />
      )}
    </div>
  );
}
